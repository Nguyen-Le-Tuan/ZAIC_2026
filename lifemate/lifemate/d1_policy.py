"""D1 label policy ("programme first"): which read calls a gold label carries, derived from the catalog alone.

The organisers' labels look generated by a programme (docs/SYNTH_DATA_PLAN_2026-11-08.md section 1.1). This module is
that programme as far as the catalog describes it, so that synthetic samples for apps without train labels get the
same conventions:

  * an ID a write needs (a parameter with `x-ref`) is fetched with the read tool whose `returns` names that
    collection, unless the ID is already known (history tool results, or a result earlier in the turn);
  * that read carries its required arguments, plus `query` when it has one (the stored name of the entity);
    no other optional filter.

Nothing here is fitted per app: the rule reads `kind`, `x-ref`, `returns` and `required` only. scripts/d1_gate0.py
replays it against the train labels (gate 0 of D1).
"""
from __future__ import annotations

import collections
import json

QUERY_KEYS = ("query",)          # free-text search key of a read tool
NAME_FIELDS = ("name", "title")  # where an entity keeps the name a query uses


def atoms(x, out: set | None = None) -> set:
    """Scalar values of a JSON value, as strings (what a later call could copy from a result)."""
    out = set() if out is None else out
    if isinstance(x, dict):
        for v in x.values():
            atoms(v, out)
    elif isinstance(x, list):
        for v in x:
            atoms(v, out)
    elif isinstance(x, bool) or x is None:
        pass
    elif isinstance(x, (int, float)):
        out.add(str(x))
    elif isinstance(x, str) and len(x) >= 2:
        out.add(x)
    return out


def xref_values(tool: dict, args: dict) -> list[tuple[str, str, object]]:
    """[(parameter path, collection, value)] for every x-ref value of a call, nested ones included."""
    out = []

    def walk(path, spec, v):
        if "x-ref" in spec:
            for x in (v if isinstance(v, list) else [v]):
                if isinstance(x, (str, int)) and not isinstance(x, bool):
                    out.append((path, spec["x-ref"], x))
            return
        if spec.get("type") == "array" and isinstance(v, list):
            it = spec.get("items", {})
            for x in v:
                walk(path, it, x)
        elif spec.get("type") == "object" and isinstance(v, dict):
            for k, s in spec.get("properties", {}).items():
                if k in v:
                    walk(f"{path}.{k}", s, v[k])

    for k, spec in tool.get("parameters", {}).get("properties", {}).items():
        if k in args:
            walk(k, spec, args[k])
    return out


def reader_index(tools: dict) -> dict[str, list[str]]:
    """{"app.collection": [read tools whose `returns` names it]}."""
    idx = collections.defaultdict(list)
    for name, t in tools.items():
        if t.get("kind") != "read" or not t.get("returns"):
            continue
        app = name.split(".")[0]
        for part in str(t["returns"]).replace(",", " ").split():
            col = part.strip("[]{}").split(".")[0]
            if col:
                idx[f"{app}.{col}"].append(name)
    return dict(idx)


def canonical_readers(col: str, tools: dict, idx: dict[str, list[str]]) -> list[str]:
    """Read tools that can supply an ID of `col`, best first.
    1) tools whose `returns` names the collection, those that do not need an ID of the same collection first
       (contacts.search before contacts.get), then those with a `query` (news.search before news.headlines: 9/9 train
       labels that need an article ID search for it);
    2) no tool declares it (smart_home.scenes, ride_hailing.rides): the app's read tools without required arguments."""
    def rank(n):
        t = tools[n]
        req = set(t["parameters"].get("required", []))
        needs_same = any(p in req and s.get("x-ref") == col for p, s in t["parameters"]["properties"].items())
        return (needs_same, not any(k in t["parameters"]["properties"] for k in QUERY_KEYS))
    cands = sorted(idx.get(col, []), key=rank)
    if cands:
        return cands
    app = col.split(".")[0]
    return [n for n, t in tools.items() if n.startswith(app + ".") and t.get("kind") == "read"
            and not t["parameters"].get("required")]


def entity_name(entity: dict | None) -> str | None:
    if not isinstance(entity, dict):
        return None
    for f in NAME_FIELDS:
        if isinstance(entity.get(f), str) and entity[f]:
            return entity[f]
    return None


def read_args(tool: dict, entity: dict | None, slots: dict | None = None) -> dict | None:
    """Arguments of the ID read: required ones and `query`. `entity` is the object the scenario targets; `slots` are
    values only the scenario knows (required arguments that are not a query, e.g. flights.search origin/date).
    None when a required argument cannot be filled."""
    params = tool["parameters"]
    req = list(params.get("required", []))
    args = {}
    for k in params["properties"]:
        if k in QUERY_KEYS:
            name = entity_name(entity)
            if name is not None:
                args[k] = name
            elif k in req:
                return None
        elif k in req:
            if slots is None or k not in slots:
                return None
            args[k] = slots[k]
    return args


def call_key(call: dict) -> str:
    return json.dumps([call["name"], call["arguments"]], sort_keys=True, ensure_ascii=False)
